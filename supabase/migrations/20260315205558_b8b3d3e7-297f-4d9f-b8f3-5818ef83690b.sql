ALTER TABLE public.profiles ADD COLUMN is_deleted boolean NOT NULL DEFAULT false;
ALTER TABLE public.profiles ADD COLUMN deleted_name text;

-- Update handle_new_user to support admin role from metadata
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  INSERT INTO public.profiles (id, full_name)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.email));
  
  INSERT INTO public.user_roles (user_id, role)
  VALUES (NEW.id, COALESCE((NEW.raw_user_meta_data->>'role')::app_role, 'member'));
  
  RETURN NEW;
END;
$function$;